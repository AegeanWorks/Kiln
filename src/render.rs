//! Pure renderers. Byte-for-byte deterministic for a given dataset.

use crate::model::{Dataset, Format, Rendered, Value, Verdict};

fn json_string(value: &str) -> String {
    let mut out = String::from("\"");
    for c in value.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            '\n' => out.push_str("\\n"),
            '\r' => out.push_str("\\r"),
            '\t' => out.push_str("\\t"),
            c if (c as u32) < 0x20 => out.push_str(&format!("\\u{:04x}", c as u32)),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

fn scalar(value: &Value) -> String {
    match value {
        Value::Int(number) => number.to_string(),
        Value::Float(cents) => format!("{}.{:02}", cents / 100, cents % 100),
        Value::Bool(flag) => flag.to_string(),
        Value::Str(text) => text.clone(),
        Value::List(items) => {
            let parts: Vec<String> = items.iter().map(scalar).collect();
            parts.join("|")
        }
    }
}

fn json_value(value: &Value) -> String {
    match value {
        Value::Str(text) => json_string(text),
        Value::List(items) => {
            let parts: Vec<String> = items.iter().map(json_value).collect();
            format!("[{}]", parts.join(", "))
        }
        other => scalar(other),
    }
}

/// Pretty JSON with declaration-order keys and stable two-space indentation.
pub fn render_json(dataset: &Dataset) -> String {
    let mut out = String::from("{\n");
    out.push_str(&format!("  \"record\": {},\n", json_string(&dataset.record)));
    out.push_str(&format!("  \"count\": {},\n", dataset.records.len()));

    let fields: Vec<String> = dataset.columns.iter().map(|name| json_string(name)).collect();
    out.push_str(&format!("  \"fields\": [{}],\n", fields.join(", ")));

    if dataset.records.is_empty() {
        out.push_str("  \"rows\": []\n");
    } else {
        out.push_str("  \"rows\": [\n");
        for (row_index, row) in dataset.records.iter().enumerate() {
            out.push_str("    {\n");
            for (field_index, (name, value)) in row.values.iter().enumerate() {
                let comma = if field_index + 1 == row.values.len() { "" } else { "," };
                out.push_str(&format!("      {}: {}{}\n", json_string(name), json_value(value), comma));
            }
            let comma = if row_index + 1 == dataset.records.len() { "" } else { "," };
            out.push_str(&format!("    }}{}\n", comma));
        }
        out.push_str("  ]\n");
    }
    out.push_str("}\n");
    out
}

fn csv_cell(value: &str) -> String {
    if value.contains(',') || value.contains('"') || value.contains('\n') || value.contains('\r') {
        format!("\"{}\"", value.replace('"', "\"\""))
    } else {
        value.to_string()
    }
}

/// RFC-4180-style CSV: one header row, one row per record, stable field order.
pub fn render_csv(dataset: &Dataset) -> String {
    let header: Vec<String> = dataset.columns.iter().map(|name| csv_cell(name)).collect();
    let mut out = format!("{}\n", header.join(","));
    for row in &dataset.records {
        let cells: Vec<String> = row.values.iter().map(|(_, value)| csv_cell(&scalar(value))).collect();
        out.push_str(&format!("{}\n", cells.join(",")));
    }
    out
}

/// Dispatch to the selected renderer and attach output metadata.
pub fn render(dataset: &Dataset, format: Format) -> Rendered {
    let text = match format {
        Format::Json => render_json(dataset),
        Format::Csv => render_csv(dataset),
    };
    Rendered {
        format,
        bytes: text.len(),
        records: dataset.records.len(),
        text,
    }
}

/// One-line verdict used by the comparison gate.
pub fn render_verdict(verdict: Verdict) -> String {
    match verdict {
        Verdict::Pass => "fixture MATCH: generated bytes equal the committed fixture\n".to_string(),
        Verdict::Fail => "fixture DIFFER: generated bytes do not match the committed fixture\n".to_string(),
    }
}
